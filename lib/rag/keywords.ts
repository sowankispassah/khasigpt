export function buildRagKeywordQuery(query: string): string {
  const tokens = query.normalize("NFKC").match(/[\p{L}\p{M}\p{N}]+/gu) ?? [];
  return tokens
    .filter((token) => token.length >= 3)
    .filter((token) => !RAG_KEYWORD_STOP_WORDS.has(token.toLowerCase()))
    .join(" ");
}
